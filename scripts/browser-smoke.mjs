import { chromium } from '@playwright/test';
import fs from 'node:fs';
fs.mkdirSync('.local', { recursive: true });
const base = process.env.GAME_URL || 'http://127.0.0.1:5173/';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const errors = [];
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await ctx.newPage();
page.on('pageerror', e => errors.push(e.message));
await page.goto(base);
await page.locator('.scene-host.ready canvas').waitFor({ timeout: 20000 });
if (await page.locator('.facts, .intro, .how, footer').count()) throw new Error('Homepage contains marketing UI');
if (await page.locator('#join-form').isVisible()) throw new Error('Join form must start collapsed');
await page.locator('#join-menu').click();
await page.locator('#room-input').fill('ABCD2345');
await page.locator('#rules').click();
await page.locator('#close-rules').click();
if (await page.locator('#room-input').inputValue() !== 'ABCD2345') throw new Error('Menu lost room draft');
await page.locator('#join-menu').click();
if (await page.evaluate(() => document.documentElement.scrollHeight > innerHeight)) throw new Error('Desktop menu exceeds viewport');
await page.screenshot({ path: '.local/desktop.png', fullPage: true });
await page.locator('#nickname').fill('测试巫师');
await page.locator('#practice').click();
await page.locator('.lobby-scene .scene-host.ready canvas').waitFor();
if (await page.locator('.seats .seat').count() !== 6) throw new Error('Lobby must have six seats');
await page.locator('[data-remove]').last().click();
if (await page.locator('#start').isEnabled()) throw new Error('Two players cannot start');
await page.locator('#addbot').click();
if (!await page.locator('#start').isEnabled()) throw new Error('Three players should be able to start');
await page.screenshot({ path: '.local/lobby-desktop.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: '.local/lobby-mobile.png', fullPage: true });
if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth || document.documentElement.scrollHeight > innerHeight)) throw new Error('Lobby mobile overflow');
await page.setViewportSize({ width: 1440, height: 1000 });
await page.locator('#start').click();
await page.locator('.table .scene-host.ready canvas').waitFor();
const tableFillsScreen = await page.locator('.table').evaluate(el => {
  const r = el.getBoundingClientRect();
  return r.x === 0 && r.y === 0 && Math.abs(r.width - innerWidth) < 2 && Math.abs(r.height - innerHeight) < 2;
});
if (!tableFillsScreen || await page.locator('.game-layout aside').isVisible()) throw new Error('Game must start with a full viewport table and closed score panel');
await page.screenshot({ path: '.local/fullscreen-table.png', fullPage: true });
for (let step = 0; step < 400; step++) {
  if (await page.locator('#rematch').count()) break;
  if (await page.locator('[data-trump]').count()) await page.locator('[data-trump]').first().click();
  else if (await page.locator('[data-bid]').count()) await page.locator('[data-bid]').first().click();
  else if (await page.locator('.hand .playable').count()) await page.locator('.hand .playable').first().click();
  else if (await page.locator('#next').count()) await page.locator('#next').click();
  else await page.waitForTimeout(180);
}
if (!await page.locator('#rematch').count()) throw new Error('Practice game did not finish');
if (await page.locator('.scene-host canvas').count() !== 1) throw new Error('Expected one persistent 3D canvas');
await page.screenshot({ path: '.local/game.png', fullPage: true });
await page.setViewportSize({ width: 390, height: 844 });
await page.screenshot({ path: '.local/mobile-game.png', fullPage: true });
if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Mobile horizontal overflow');
const mobile = await ctx.newPage();
await mobile.setViewportSize({ width: 390, height: 844 });
await mobile.goto(base);
await mobile.locator('.scene-host.ready canvas').waitFor({ timeout: 20000 });
await mobile.screenshot({ path: '.local/mobile.png', fullPage: true });
if (await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth)) throw new Error('Landing mobile overflow');
if (await mobile.evaluate(() => document.documentElement.scrollHeight > innerHeight)) throw new Error('Mobile menu exceeds viewport');
await mobile.goto(`${base}?room=ABCD2345`);
if (!await mobile.locator('#join-form').isVisible() || await mobile.locator('#room-input').inputValue() !== 'ABCD2345') throw new Error('Invitation must open join form');
await browser.close();
const fallbackBrowser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--disable-webgl'] });
const fallbackPage = await fallbackBrowser.newPage();
await fallbackPage.goto(base);
await fallbackPage.getByRole('button', { name: 'WebGL 不可用，已自动使用二维界面' }).waitFor();
await fallbackPage.locator('#practice').click();
await fallbackPage.locator('#start').click();
await fallbackPage.locator('.hand .card').first().waitFor();
await fallbackBrowser.close();
console.log(JSON.stringify({ practice: '5-round game complete with WebGL', mobile: 'no overflow', fallback: '2D game starts without WebGL', errors }));
if (errors.length) process.exitCode = 1;
